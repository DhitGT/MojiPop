import { test, expect } from '@playwright/test'

test('theme toggle persists across navigation and reload, including the practice arena', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto('/belajar')
  const toggle = page.getByRole('button', { name: 'Mode gelap', exact: true })
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await toggle.click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(21, 22, 34)')
  await page.getByRole('link', { name: 'Pengaturan', exact: true }).click()
  await expect(page.getByLabel('Tema aplikasi')).toHaveValue('dark')
  await page.reload()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.settings-simple .panel').first()).toHaveCSS('background-color', 'rgb(32, 34, 50)')
  await page.goto('/latihan?script=hiragana&kind=letter&format=choice&items=hiragana%3A%E3%81%82')
  await page.getByRole('button', { name: 'Mulai latihan', exact: true }).click()
  await expect(page.locator('.arena-card')).toHaveCSS('background-color', 'rgb(32, 34, 50)')
  await toggle.click()
  await expect(page.locator('html')).not.toHaveClass(/dark/)
  await page.reload()
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
})

test('system theme reacts to device changes and the toggle works on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/pengaturan')
  await page.getByLabel('Tema aplikasi').selectOption('system')
  await expect(page.locator('html')).toHaveClass(/dark/)
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).not.toHaveClass(/dark/)
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveClass(/dark/)
  await page.getByRole('button', { name: 'Mode gelap', exact: true }).click()
  await expect(page.getByLabel('Tema aplikasi')).toHaveValue('light')
  await page.emulateMedia({ colorScheme: 'light' })
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).not.toHaveClass(/dark/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
