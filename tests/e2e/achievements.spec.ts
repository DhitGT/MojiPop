import { test, expect } from '@playwright/test'

for (const width of [1280, 390]) {
  test(`achievements unlock from practice and persist at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/achievement')
    await expect(page.getByRole('heading', { name: 'Achievement', exact: true })).toBeVisible()
    await expect(page.locator('.achievement-row')).toHaveCount(84)
    await expect(page.locator('.achievement-row.is-earned')).toHaveCount(0)
    await expect(page.locator('.badge-silhouette')).toHaveCount(84)
    await expect(page.locator('.is-locked h3')).toHaveCount(0)
    await expect(page.locator('.achievement-alert-dot')).toHaveCount(0)
    await expect(page.locator('.achievement-gallery').first()).toHaveCSS('display', 'grid')
    await page.goto('/latihan?script=hiragana&kind=letter&items=hiragana%3A%E3%81%82')
    await page.getByRole('button', { name: 'Mulai latihan', exact: true }).click()
    for (let index = 0; index < 10; index++) {
      await expect(page.locator('#answer')).toBeEditable()
      await page.locator('#answer').fill('a')
      await page.locator('#answer').press('Enter')
      if (index === 0) {
        await expect(page.locator('.achievement-notification')).toContainText('terbuka!')
        await page.getByRole('button', { name: 'Tutup notifikasi achievement' }).click()
      }
      if (index < 9) await expect(page.locator('#answer')).toHaveValue('')
    }
    await expect(page).toHaveURL(/\/hasil\//)
    await expect(page.locator('.achievement-alert-dot')).toBeVisible()
    await page.reload()
    await expect(page.locator('.achievement-alert-dot')).toBeVisible()
    await page.locator('nav').getByRole('link', { name: /Achievement/ }).click()
    await expect(page.getByRole('heading', { name: 'Baru didapat!' })).toBeVisible()
    await expect(page.locator('.achievement-new-list')).toContainText('Jawaban benar')
    await expect(page.locator('.achievement-alert-dot')).toHaveCount(0)
    await expect(page.locator('[data-achievement="correct-10"]')).toBeVisible()
    await expect(page.locator('[data-achievement="correct-25"]')).toHaveClass(/is-locked/)
    await expect(page.locator('[data-achievement="sessions-1"]')).toBeVisible()
    await expect(page.locator('[data-achievement="perfect-1"]')).toBeVisible()
    await expect(page.locator('[data-achievement="mastered-1"]')).toHaveClass(/is-locked/)
    const count = await page.locator('.achievement-row.is-earned').count()
    expect(count).toBeGreaterThanOrEqual(8)
    await expect(page.locator('.is-earned svg.achievement-badge:not(.badge-silhouette)')).toHaveCount(count)
    await expect(page.locator('.badge-silhouette')).toHaveCount(84 - count)
    await expect(page.locator('[data-achievement="correct-10"] .achievement-badge')).toHaveAttribute('data-tier', '2')
    await expect(page.locator('[data-achievement="perfect-1"] .achievement-badge')).toHaveAttribute('data-category', 'perfect')
    await page.reload()
    await expect(page.locator('.achievement-row.is-earned')).toHaveCount(count)
    await expect(page.locator('.achievement-new-panel')).toHaveCount(0)
    await expect(page.locator('.achievement-alert-dot')).toHaveCount(0)
    await expect(page.locator('.is-locked h3')).toHaveCount(0)
    await expect(page.locator('.achievement-notification')).not.toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    const row = await page.locator('.achievement-row').first().boundingBox()
    expect(row!.width).toBeGreaterThan(row!.height * 1.8)
    await page.screenshot({ path: `test-results/achievements-${width}.png` })
    await page.getByRole('button', { name: 'Mode gelap', exact: true }).click()
    await page.screenshot({ path: `test-results/achievements-dark-${width}.png` })
    expect(errors).toEqual([])
  })
}
