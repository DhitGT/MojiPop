import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function start(page: import('@playwright/test').Page, query = 'script=hiragana&kind=letter&items=hiragana%3Aあ') {
  await page.goto(`/latihan?${query}`)
  await page.getByRole('button', { name: 'Mulai latihan', exact: true }).click()
  await expect(page.locator('#answer')).toBeEnabled()
}

async function openReset(page: import('@playwright/test').Page) {
  const button = page.getByRole('button', { name: 'Reset progres', exact: true })
  if (!await button.isVisible()) await page.locator('summary').filter({ hasText: /^Reset progres$/ }).click()
  await button.click()
}
test('a new learner can study, finish ten questions, and retain progress after reload', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Mau belajar apa?' })).toBeVisible()
  await page.screenshot({ path: 'test-results/desktop-home.png', fullPage: true })
  await page.getByRole('link', { name: /Mulai belajar/ }).click()
  await expect(page.getByRole('heading', { name: 'Materi' })).toBeVisible()
  await page.locator('.letter-tile').filter({ has: page.locator('.letter-glyph', { hasText: /^あ$/ }) }).click()
  await page.getByRole('button', { name: 'Lihat bacaan' }).click()
  await expect(page.locator('.reading')).toHaveText('a')
  await page.getByRole('link', { name: 'Latih huruf ini' }).click()
  await page.getByRole('button', { name: 'Mulai latihan', exact: true }).click()
  for (let index = 0; index < 10; index++) {
    await expect(page.locator('#answer')).toBeEditable()
    await page.locator('#answer').fill(' A ')
    await page.locator('#answer').press('Enter')
    await expect(page.getByText('Benar', { exact: true })).toBeVisible()
    if (index < 9) await expect(page.locator('#answer')).toHaveValue('')
  }
  await expect(page).toHaveURL(/\/hasil\//)
  await expect(page.getByText('100%', { exact: true })).toBeVisible()
  await expect(page.locator('.answer-details tbody tr')).toHaveCount(10)
  await page.reload()
  await expect(page.getByText('100%', { exact: true })).toBeVisible()
  await page.goto('/progres')
  await expect(page.getByText('10 / 10', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

