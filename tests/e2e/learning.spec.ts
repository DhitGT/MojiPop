test('arena remains usable after rotation and a shorter mobile viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await start(page, 'script=hiragana&kind=word&items=word%3Aがっこう')
  await expect(page.locator('.arena-prompt')).toHaveText('がっこう')
  for (const viewport of [{ width: 844, height: 390 }, { width: 390, height: 460 }]) {
    await page.setViewportSize(viewport)
    await page.locator('#answer').scrollIntoViewIfNeeded()
    await expect(page.locator('#answer')).toBeInViewport()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    const hit = await page.locator('#answer').evaluate(input => {
      const rect = input.getBoundingClientRect()
      const covering = document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2)
      return { matches: covering === input, covering: covering?.outerHTML.slice(0, 200), y: rect.y, height: rect.height, viewport: innerHeight }
    })
    expect(hit.matches, JSON.stringify(hit)).toBeTruthy()
  }
  await page.screenshot({ path: 'test-results/mobile-arena-short.png', fullPage: true })
  await page.locator('#answer').fill('gakkou')
  await page.locator('#answer').press('Enter')
  await expect(page.getByText('Benar', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Akhiri sesi' }).click()
  await expect(page).toHaveURL(/\/hasil\//)
  await expect(page.locator('table').last().locator('tbody tr')).toHaveCount(1)
  await expect(page.getByText('100%', { exact: true })).toBeVisible()
})
