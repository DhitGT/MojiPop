test('a hidden tab pauses Sprint and resume replaces the unanswered prompt', async ({ page }) => {
  await page.clock.install()
  await page.goto('/latihan?script=hiragana&kind=letter&items=hiragana%3Aあ,hiragana%3Aい')
  await page.getByRole('button', { name: /Sprint 60 detik/ }).click()
  await page.getByRole('button', { name: 'Mulai latihan', exact: true }).click()
  await expect(page.locator('#answer')).toBeEnabled()
  const original = await page.locator('.arena-prompt').textContent()
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, value: true })
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(page.getByRole('heading', { name: 'Sesi dijeda' })).toBeVisible()
  await page.clock.runFor(65000)
  await expect(page).toHaveURL(/\/arena\?/)
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, value: false })
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await page.getByRole('button', { name: /Lanjutkan sesi/ }).click()
  await expect(page.locator('#answer')).toBeEnabled()
  await expect(page.locator('.arena-prompt')).not.toHaveText(original || '')
  await expect(page.getByText(/0 benar mandiri/)).toBeVisible()
  await expect(page.getByRole('timer')).toContainText(/(59|60) dtk/)
  await page.clock.runFor(61000)
  await expect(page).toHaveURL(/\/hasil\//)
  await expect(page.getByText('◌ 1 tidak selesai', { exact: true })).toBeVisible()
  await page.getByText('Detail skor', { exact: true }).click()
  await expect(page.getByText(/Sesi pernah dijeda/)).toBeVisible()
  await expect(page.getByText(/Rekor baru/)).not.toBeVisible()
})

