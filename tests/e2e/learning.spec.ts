test('export, confirmed reset, and validated import restore the original attempts once', async ({ page }) => {
  await start(page)
  await page.locator('#answer').fill('a')
  await page.locator('#answer').press('Enter')
  await expect(page.getByText('Benar', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Akhiri sesi' }).click()
  await expect(page).toHaveURL(/\/hasil\//)
  await page.goto('/pengaturan')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Unduh cadangan' }).click()
  const downloaded = await downloadPromise
  const buffer = await readFile((await downloaded.path())!)
  const backup = JSON.parse(buffer.toString('utf8'))
  expect(backup.sessions).toHaveLength(1)
  expect(backup.sessions[0].attempts).toHaveLength(1)
  expect(backup.sessions[0].attempts[0].answeredAt).toBeTruthy()

  await openReset(page)
  await page.getByRole('button', { name: 'Ya, reset progres' }).click()
  await expect(page.getByRole('status')).toContainText('sudah direset')
  await page.goto('/progres')
  await expect(page.getByRole('heading', { name: 'Belum ada latihan' })).toBeVisible()
  await page.goto('/pengaturan')
  await page.locator('#import-file').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer })
  await expect(page.getByRole('dialog')).toContainText('Cadangan berisi 1 sesi')
  await page.getByRole('button', { name: 'Ya, ganti progres' }).click()
  await expect(page.getByRole('status')).toContainText('berhasil dipulihkan')
  await page.goto('/progres')
  await expect(page.getByText('1 / 1', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('1 / 1', { exact: true })).toBeVisible()
  await page.goto(`/hasil/${backup.sessions[0].id}`)
  await expect(page.locator('.answer-details tbody tr')).toHaveCount(1)
})

test('storage quota failure keeps answers in memory and allows their export', async ({ page }) => {
  await page.addInitScript(() => {
    const originalPut = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args: Parameters<typeof originalPut>) {
      if (this.name === 'sessions') throw new DOMException('Storage penuh', 'QuotaExceededError')
      return originalPut.apply(this, args)
    }
  })
  await start(page)
  await expect(page.getByRole('alert')).toContainText('Progres belum bisa disimpan')
  await page.locator('#answer').fill('a')
  await page.locator('#answer').press('Enter')
  await expect(page.getByText('Benar', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Akhiri sesi' }).click()
  await expect(page).toHaveURL(/\/hasil\//)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Ekspor data sekarang' }).click()
  const backup = JSON.parse(await readFile((await (await downloadPromise).path())!, 'utf8'))
  expect(backup.sessions[0].attempts).toHaveLength(1)
  expect(backup.sessions[0].attempts[0].outcome).toBe('correct')
})

