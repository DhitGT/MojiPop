import { expect, test } from '@playwright/test'
test.use({ storageState: { cookies: [], origins: [] } })

test('landing demo, language selection, and learning entry work', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (/hydration/i.test(message.text())) errors.push(message.text()) })
  await page.goto('/')
  await expect(page.locator('.landing')).toHaveAttribute('data-ready', 'true')
  await expect(page.locator('#lp-title')).toContainText('Dari asing,')
  await expect(page.locator('dialog[open]')).toHaveCount(0)
  await page.locator('.lp-kiko .mascot-frame-open').evaluate((image: HTMLImageElement) => image.decode())
  await page.screenshot({ path: '.cache/landing-preview/landing-desktop.png', fullPage: true })
  await page.locator('.lp-demo-choices').getByRole('button', { name: 'i', exact: true }).click()
  await expect(page.locator('.lp-demo-feedback')).toContainText('Belum tepat')
  await page.locator('.lp-demo-choices').getByRole('button', { name: 'a', exact: true }).click()
  await expect(page.locator('.lp-demo-feedback')).toContainText('Betul!')
  await page.getByRole('button', { name: '🇰🇷 Korea', exact: true }).click()
  await expect(page.locator('.lp-demo-glyph')).toHaveText('나')
  await expect(page.locator('.lp-demo-feedback')).toContainText('Pilih salah satu')
  await page.locator('.lp-demo-choices').getByRole('button', { name: 'na', exact: true }).click()
  await expect(page.locator('.lp-demo-feedback')).toContainText('Betul!')
  await page.locator('summary').filter({ hasText: 'Harus buat akun dulu?' }).click()
  await expect(page.locator('details[open]')).toContainText('Tidak. Kamu bisa langsung')
  await page.getByRole('button', { name: /Bahasa Korea/ }).click()
  await expect(page).toHaveURL(/\/belajar$/)
  await expect(page.getByRole('heading', { name: 'Mau belajar apa?' })).toBeVisible()
  await expect(page.locator('.quest-label')).toHaveText('Hangul')
  await expect(page.locator('dialog[open]')).toHaveCount(0)
  expect(errors).toEqual([])
})

test('landing fits phone screens and opens the existing dashboard', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  await expect(page.locator('.landing')).toHaveAttribute('data-ready', 'true')
  await expect(page.getByRole('button', { name: 'Mulai belajar gratis' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.locator('.lp-kiko .mascot-frame-open').evaluate((image: HTMLImageElement) => image.decode())
  await page.screenshot({ path: '.cache/landing-preview/landing-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Mulai belajar gratis' }).click()
  await expect(page).toHaveURL(/\/belajar$/)
  await expect(page.getByRole('heading', { name: 'Mau belajar apa?' })).toBeVisible()
})

test('interactive mascot, feature previews, and reduced motion work', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.landing')).toHaveAttribute('data-ready', 'true')
  await page.locator('.lp-mascot-button').getByRole('button', { name: 'Sapa Kiko', exact: true }).click()
  await expect(page.locator('.lp-speech')).toContainText('Klik hurufnya')
  // Floating cards intentionally move continuously; target their current position.
  await page.getByRole('button', { name: 'Balik kartu Hiragana' }).click({ force: true })
  await expect(page.locator('.lp-glyph-ja')).toContainText('DIBACA: A')
  await expect(page.locator('.lp-kiko .kiko-idle')).not.toHaveCSS('animation-name', 'none')
  await expect(page.locator('.lp-kiko .mascot-frame-closed')).not.toHaveCSS('animation-name', 'none')
  await page.locator('#lp-race-input').fill('sak')
  await expect(page.locator('.lp-race-word .typed')).toHaveCount(3)
  await page.locator('#lp-race-input').fill('sakura')
  await expect(page.locator('.lp-race-avatar svg')).toBeVisible()
  await expect(page.locator('.lp-race-status')).toContainText('Finish!')
  await page.getByRole('button', { name: 'Ulangi' }).click()
  await expect(page.locator('#lp-race-input')).toHaveValue('')
  await page.getByRole('tab', { name: 'Perjalanan Belajar' }).click()
  await expect(page.getByRole('tabpanel')).toContainText('Lima huruf pertama')
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tabpanel')).toContainText('Setiap latihan terlihat.')
  await expect(page.getByRole('tab', { name: 'Progres & Achievement' })).toBeFocused()
  await expect(page.getByRole('link', { name: 'Powered by dheep.site' })).toHaveAttribute('href', 'https://dheep.site')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.lp-kiko .kiko-idle')).toHaveCSS('animation-name', 'none')
  await page.setViewportSize({ width: 375, height: 812 })
  await page.getByRole('tab', { name: 'Typing Race' }).click()
  await page.locator('#lp-race-input').fill('sakura')
  await expect(page.locator('.lp-race-status')).toContainText('Finish!')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '.cache/landing-preview/landing-feature-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
