import { test, expect, type Page } from '@playwright/test'
import { content } from '../../app/data/content'
import { campaignChapters, chapterQuiz, placementBlocks } from '../../app/utils/campaign'

async function interview(page: Page, script = 'Hiragana', experience = 'Baru mulai') {
  const dialog = page.getByRole('dialog', { name: 'Kita mulai dari mana?' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: script, exact: true }).click()
  await page.getByRole('button', { name: 'Lanjut', exact: true }).click()
  await page.getByRole('radio', { name: new RegExp(experience) }).check()
  for (let index = 0; index < 3; index++) await page.getByRole('button', { name: 'Lanjut', exact: true }).click()
  await page.getByRole('button', { name: 'Lanjut ke tes penempatan' }).click()
}

test('guided journey places a beginner, resumes quizzes, gates chapters, and preserves separate tracks', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const chapters = campaignChapters('hiragana', content)
  await page.goto('/perjalanan')
  await expect(page.getByRole('heading', { name: 'Kita mulai dari mana?' })).toBeVisible()
  await interview(page)
  await page.getByRole('button', { name: 'Belum tahu', exact: true }).click()
  await page.reload()
  await expect(page.getByText('Soal 2 · maksimal', { exact: false })).toBeVisible()
  for (let index = 0; index < 2; index++) await page.getByRole('button', { name: 'Belum tahu', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Mulai dari bab 1: Vokal' })).toBeVisible()
  await page.getByRole('button', { name: 'Gunakan titik mulai ini' }).click()
  await expect(page.locator('.journey-path-card')).toHaveCount(3)
  await expect(page.locator('.journey-path-card.selected .journey-path-position')).toHaveText(`Bab 1 / ${chapters.length}`)
  await expect(page.locator('.journey-path-card.selected progress')).toHaveAttribute('value', '0')
  await expect(page.locator('.journey-chapter').nth(1)).toBeDisabled()
  await page.getByRole('button', { name: 'Lanjutkan belajar' }).click()
  await expect(page.locator('.journey-card')).toHaveCount(5)
  await page.getByRole('button', { name: 'Sudah dipelajari, mulai kuis' }).click()
  await page.getByRole('button', { name: 'Belum tahu', exact: true }).click()
  await page.reload()
  await expect(page.getByText(`Soal 2 dari ${chapterQuiz(chapters[0]!).length}`, { exact: false })).toBeVisible()
  for (let index = 1; index < chapterQuiz(chapters[0]!).length; index++) await page.getByRole('button', { name: 'Belum tahu', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pelan-pelan, kita kuatkan dulu' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Bagian yang perlu diulang' })).toBeVisible()
  await page.getByRole('button', { name: '← Peta perjalanan', exact: true }).click()
  await expect(page.locator('.journey-chapter').nth(1)).toBeDisabled()
  await page.getByRole('button', { name: 'Lanjutkan belajar' }).click()
  await page.getByRole('button', { name: 'Ulangi kuis', exact: true }).click()
  for (const item of chapterQuiz(chapters[0]!)) {
    await page.getByLabel('Ketik bacaannya dengan huruf Latin').fill(item.answer)
    await page.getByRole('button', { name: 'Kirim jawaban' }).click()
  }
  await expect(page.getByRole('heading', { name: 'Satu langkah lagi dikuasai!' })).toBeVisible()
  await expect(page.locator('.journey-score')).toHaveText('100%')
  await page.getByRole('button', { name: '← Peta perjalanan', exact: true }).click()
  await expect(page.locator('.journey-chapter').nth(1)).toBeEnabled()
  await expect(page.locator('.journey-path-card.selected .journey-path-position')).toHaveText(`Bab 2 / ${chapters.length}`)
  await expect(page.locator('.journey-path-card.selected progress')).toHaveAttribute('value', '1')
  await expect(page.getByRole('button', { name: 'Hangul', exact: true }).locator('progress')).toHaveAttribute('value', '0')
  await expect(page.getByText(`1 / ${chapters.length} bab selesai`)).toBeVisible()
  await page.getByRole('button', { name: 'Hangul', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Kita mulai dari mana?' })).toBeVisible()
  await page.getByRole('button', { name: 'Hiragana', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Satu langkah lagi dikuasai!' })).toBeVisible()
  await page.getByRole('button', { name: 'Lanjut ke bab berikutnya' }).click()
  await expect(page.getByRole('heading', { name: 'K', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/journey-mobile-lesson.png', fullPage: true })
  await page.getByRole('button', { name: '← Peta perjalanan', exact: true }).click()
  await page.getByRole('button', { name: 'Atur ulang penempatan', exact: true }).click()
  await page.getByRole('button', { name: 'Batal', exact: true }).click()
  await expect(page.getByText(`1 / ${chapters.length} bab selesai`)).toBeVisible()
  await page.screenshot({ path: 'test-results/journey-mobile-map.png', fullPage: true })
  expect(errors).toEqual([])
})

test('placement uses consecutive test blocks and keeps skipped chapters available for review', async ({ page }) => {
  const chapters = campaignChapters('katakana', content)
  const blocks = placementBlocks(chapters)
  await page.goto('/perjalanan')
  await interview(page, 'Katakana', 'Sudah kenal beberapa')
  for (const item of blocks[0]!.items) {
    await page.getByLabel('Ketik bacaannya dengan huruf Latin').fill(item.answer)
    await page.getByRole('button', { name: 'Kirim jawaban' }).click()
  }
  for (let index = 0; index < 3; index++) await page.getByRole('button', { name: 'Belum tahu', exact: true }).click()
  await expect(page.getByRole('heading', { name: new RegExp(`Mulai dari bab ${blocks[1]!.startIndex + 1}:`) })).toBeVisible()
  await page.getByRole('button', { name: 'Gunakan titik mulai ini' }).click()
  await expect(page.getByText(`0 / ${chapters.length} bab selesai`)).toBeVisible()
  await expect(page.locator('.journey-chapter').nth(0)).toBeEnabled()
  await expect(page.locator('.journey-chapter').nth(blocks[1]!.startIndex)).toBeEnabled()
  await expect(page.locator('.journey-chapter').nth(blocks[1]!.startIndex + 1)).toBeDisabled()
  await page.getByRole('button', { name: 'Atur ulang penempatan', exact: true }).click()
  await page.getByRole('button', { name: 'Ulangi penempatan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Kita mulai dari mana?' })).toBeVisible()
})

test('Hangul placement and final chapter complete on a narrow screen in dark mode', async ({ page }) => {
  const chapters = campaignChapters('hangul', content)
  const blocks = placementBlocks(chapters)
  await page.setViewportSize({ width: 320, height: 800 })
  await page.goto('/perjalanan')
  await page.getByRole('button', { name: 'Nanti dulu' }).click()
  await page.locator('.theme-toggle').click()
  await page.getByRole('button', { name: 'Mulai wawancara' }).click()
  await interview(page, 'Hangul', 'Sudah cukup lancar')
  for (const item of blocks.flatMap(block => block.items)) {
    await expect(page.locator('.journey-prompt > span')).toHaveText(item.prompt)
    await page.getByLabel('Ketik bacaannya dengan huruf Latin').fill(item.answer)
    await page.getByRole('button', { name: 'Kirim jawaban' }).click()
  }
  await expect(page.getByRole('button', { name: 'Aku ingin mulai dari nol' })).toBeVisible()
  await page.getByRole('button', { name: 'Gunakan titik mulai ini' }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Lanjutkan belajar' }).click()
  await page.getByRole('button', { name: 'Sudah dipelajari, mulai kuis' }).click()
  for (const item of chapterQuiz(chapters.at(-1)!)) {
    await page.getByLabel('Ketik bacaannya dengan huruf Latin').fill(item.answer)
    await page.getByRole('button', { name: 'Kirim jawaban' }).click()
  }
  await page.getByRole('button', { name: 'Lihat perjalanan selesai' }).click()
  await expect(page.getByRole('link', { name: 'Lanjut latihan bebas' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/journey-hangul-dark.png', fullPage: true })
})

test('interview fills the screen with Kiko, shows one question, keeps answers when going back, and closes accessibly', async ({ page }) => {
  await page.goto('/perjalanan')
  const dialog = page.locator('.interview-screen')
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('.kiko-mascot')).toBeVisible()
  const bounds = await dialog.boundingBox()
  const viewport = page.viewportSize()!
  expect(bounds?.width).toBe(viewport.width)
  expect(bounds?.height).toBe(viewport.height)
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  await page.getByRole('button', { name: 'Lanjut', exact: true }).click()
  await page.getByRole('radio', { name: /Sudah kenal beberapa/ }).check()
  await expect(page.getByRole('radio')).toHaveCount(3)
  await page.getByRole('button', { name: 'Lanjut', exact: true }).click()
  await page.getByRole('radio', { name: /Mulai membaca kata/ }).check()
  await page.getByRole('button', { name: 'Kembali', exact: true }).click()
  await expect(page.getByRole('radio', { name: /Sudah kenal beberapa/ })).toBeChecked()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(dialog.locator('.kiko-mascot')).toBeVisible()
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBeTruthy()
  await page.screenshot({ path: '.cache/journey-interview-mobile.png', fullPage: true })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
  await page.getByRole('button', { name: 'Mulai wawancara' }).click()
  await page.getByRole('button', { name: 'Lanjut', exact: true }).click()
  await expect(page.getByRole('radio', { name: /Sudah kenal beberapa/ })).toBeChecked()
})
