import { test, expect } from '@playwright/test'

test('mobile controls fit and the prompt stays visible above the keyboard', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 320, height: 740 }, isMobile: true, hasTouch: true })
  await context.addInitScript(() => localStorage.setItem('kanalearn-intro-v1', 'done'))
  const page = await context.newPage()
  await page.goto('/typing-race')
  const input = page.locator('#race-input')
  await expect(input).toBeEnabled()
  for (const width of [320, 360, 390, 680, 768]) {
    await page.setViewportSize({ width, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const settings = (await page.locator('.race-settings').boundingBox())!
    for (const select of await page.locator('.race-settings select').all()) {
      const box = (await select.boundingBox())!
      expect(box.x).toBeGreaterThanOrEqual(settings.x)
      expect(box.x + box.width).toBeLessThanOrEqual(settings.x + settings.width)
      expect(box.height).toBeGreaterThanOrEqual(44)
    }
  }
  await page.setViewportSize({ width: 390, height: 844 })
  const editor = (await page.locator('.race-editor').boundingBox())!
  const source = (await page.locator('.race-source').boundingBox())!
  expect(editor.width).toBe(source.width)
  await input.tap()
  await expect(input).toBeFocused()
  // Desktop automation cannot open a system keyboard; emulate its reduced viewport.
  await page.setViewportSize({ width: 390, height: 440 })
  await expect.poll(async () => (await page.locator('.race-source').boundingBox())!.y).toBeGreaterThanOrEqual(0)
  const navigation = (await page.getByRole('navigation', { name: 'Navigasi utama' }).boundingBox())!
  const focusedEditor = (await page.locator('.race-editor').boundingBox())!
  expect(focusedEditor.y + focusedEditor.height).toBeLessThan(navigation.y)
  await input.pressSequentially('x')
  await expect(input).toHaveValue('x')
  await expect(page.locator('.race-track .wrong')).toHaveCount(1)
  await page.screenshot({ path: '.cache/typing-race-mobile-keyboard.png' })
  await page.getByRole('button', { name: 'Ulangi teks', exact: true }).tap()
  await expect(input).toHaveValue('')
  await expect(input).toBeFocused()
  await context.close()
})

test('paws travel to the actual mirrored key positions and hold between keystrokes', async ({ page }) => {
  await page.goto('/typing-race')
  const input = page.locator('#race-input')
  const mascot = page.locator('.typing-mascot')
  for (const [key, hand, x, y] of [
    ['q', 'right', 195.5, 167.5], ['v', 'right', 138.5, 151.5],
    ['p', 'left', 60.5, 167.5], ['j', 'left', 99.5, 159.5],
    ['Space', 'left', 103, 143.5], ['Space', 'right', 138, 143.5],
    ['Backspace', 'left', 46, 156]
  ] as const) {
    await input.press(key)
    await expect.poll(() => mascot.locator(`.${hand}-paw`).evaluate((paw, originX) => {
      const transform = getComputedStyle(paw).transform
      const matrix = new DOMMatrix(transform === 'none' ? undefined : transform)
      return [Math.round((originX + matrix.e) * 10) / 10, Math.round((144 + matrix.f) * 10) / 10]
    }, hand === 'left' ? 83 : 160)).toEqual([x, y])
    await expect(mascot).toHaveAttribute('data-typing', 'idle')
  }
  await page.screenshot({ path: '.cache/typing-race-moving-paws.png', fullPage: true })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(mascot.locator('.left-paw')).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
})

test('typing mascot mirrors left/right keys, space and backspace, rests, and respects reduced motion', async ({ page }) => {
  await page.clock.install()
  await page.goto('/typing-race')
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 1000))
  await page.addStyleTag({ content: '.floating-letters i { animation-play-state: paused !important; }' })
  const mascot = page.locator('.typing-mascot')
  const input = page.locator('#race-input')
  await page.locator('.race-editor').click()
  await input.pressSequentially('a')
  await expect(mascot).toHaveAttribute('data-key', 'a')
  await expect(mascot.locator('.floating-letters i')).toHaveText('a')
  await expect(mascot.locator('.right-paw')).toHaveAttribute('data-pressed', 'true')
  await expect(mascot.locator('.left-paw')).toHaveAttribute('data-pressed', 'false')
  const floatingBox = await mascot.locator('.floating-letters i').boundingBox()
  const mascotBox = await mascot.locator('svg').boundingBox()
  expect(floatingBox!.y + floatingBox!.height).toBeLessThan(mascotBox!.y)
  await expect(mascot.locator('.keyboard-keys')).toHaveAttribute('transform', 'rotate(180 121 156)')
  await input.pressSequentially('j')
  await expect(mascot.locator('.left-paw')).toHaveAttribute('data-pressed', 'true')
  await input.press('Space')
  await expect(mascot.locator('.left-paw')).toHaveAttribute('data-pressed', 'true')
  await expect(mascot.locator('.right-paw')).toHaveAttribute('data-pressed', 'true')
  await input.press('Backspace')
  await expect(mascot).toHaveAttribute('data-key', 'backspace')
  await page.screenshot({ path: '.cache/typing-race-mascot-desktop.png', fullPage: true })
  await page.clock.fastForward(250)
  await expect(mascot).toHaveAttribute('data-typing', 'idle')
  await page.clock.fastForward(900)
  await expect(mascot.locator('.floating-letters i')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await input.pressSequentially('k')
  await page.screenshot({ path: '.cache/typing-race-mascot-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await input.pressSequentially('a')
  await expect(mascot).toHaveAttribute('data-motion', 'paused')
  await expect(mascot).toHaveAttribute('data-typing', 'idle')
  await page.getByRole('button', { name: 'Ulangi teks', exact: true }).click()
  await expect(input).toHaveValue('')
  await expect(mascot).toHaveAttribute('data-typing', 'idle')
  await page.evaluate(() => { Math.random = () => .3 })
  await page.getByRole('button', { name: 'Ulangi teks', exact: true }).click()
  await expect(mascot).toHaveAttribute('data-character', 'mimi')
  await expect(mascot.locator('.mascot-frame-open')).toHaveAttribute('href', '/images/mimi-mascot.png')
  await page.evaluate(() => { Math.random = () => .01 })
  await page.getByRole('button', { name: 'Teks acak baru' }).click()
  await expect(mascot).toHaveAttribute('data-character', 'kiko')
})

test('mascot gets sleepy, focused, overwhelmed at extreme speed, and laughs after a correct streak', async ({ page }) => {
  await page.addInitScript(() => { Math.random = () => .01 })
  await page.clock.install()
  await page.goto('/typing-race')
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 1000))
  const mascot = page.locator('.typing-mascot')
  const input = page.locator('#race-input')
  await page.locator('.race-editor').click()
  await input.pressSequentially('a')
  await page.clock.fastForward(5100)
  await expect(mascot).toHaveAttribute('data-expression', 'sleepy')
  await expect(mascot.locator('.mascot-eyes-shut .mascot-frame-closed')).toHaveCSS('opacity', '1')
  await input.pressSequentially('asdfghjklqwer')
  await expect(mascot).toHaveAttribute('data-expression', 'focused')
  await page.screenshot({ path: '.cache/typing-race-mascot-focused.png', fullPage: true })
  await input.pressSequentially('asdfghjklq')
  await expect(mascot).toHaveAttribute('data-expression', 'overwhelmed')
  await expect(mascot.locator('.overwhelmed-face')).toBeVisible()
  await expect(mascot.locator('.panic-details')).toBeVisible()
  await expect(mascot.locator('.mascot-caption')).toContainText('ngebut banget')
  await page.screenshot({ path: '.cache/typing-race-mascot-overwhelmed.png', fullPage: true })
  await page.clock.fastForward(2200)
  await expect(mascot).toHaveAttribute('data-expression', 'idle')
  await input.pressSequentially('a')
  await expect(mascot).not.toHaveAttribute('data-expression', 'overwhelmed')
  await page.getByRole('button', { name: 'Ulangi teks', exact: true }).click()
  await page.getByLabel('Tampilkan petunjuk romaji').check()
  const target = (await page.locator('.race-track').innerText()).replaceAll('\u00a0', ' ').trimEnd()
  for (const char of target.slice(0, 20)) {
    await input.pressSequentially(char)
    await page.clock.fastForward(220)
  }
  await expect(mascot).toHaveAttribute('data-expression', 'laughing')
  await page.screenshot({ path: '.cache/typing-race-mascot-laughing.png', fullPage: true })
  await expect(mascot.locator('.laugh-mouth')).toHaveCount(1)
})

test('all four mascots load and react to the same mistake with different personalities', async ({ page }) => {
  await page.clock.install()
  await page.goto('/typing-race')
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 1000))
  for (const [id, random, mood, personality] of [
    ['kiko', .01, 'angry', 'Kompetitif'], ['mimi', .3, 'oops', 'Santai'],
    ['kuro', .6, 'sideeye', 'Sinis'], ['momo', .99, 'unbothered', 'Cuek']
  ] as const) {
    await page.evaluate(value => { Math.random = () => value }, random)
    await page.getByRole('button', { name: 'Ulangi teks', exact: true }).click()
    const mascot = page.locator('.typing-mascot')
    await expect(mascot).toHaveAttribute('data-character', id)
    await expect(mascot).toHaveAttribute('data-personality', new RegExp(personality))
    await expect(mascot.locator('.mascot-frame-open')).toHaveAttribute('href', `/images/${id}-mascot.png`)
    await expect(mascot.locator('.mascot-frame-closed')).toHaveAttribute('href', `/images/${id}-blink.png`)
    expect((await page.request.get(`/images/${id}-mascot.png`)).ok()).toBeTruthy()
    await page.locator('#race-input').pressSequentially('x')
    await expect(mascot).toHaveAttribute('data-expression', mood)
    await page.screenshot({ path: `.cache/typing-race-personality-${id}.png`, fullPage: true })
  }
  const sidebar = page.locator('.sidebar-companion')
  for (let i = 0; i < 4; i++) {
    await expect(sidebar.locator('img')).toHaveCount(2)
    await expect.poll(() => sidebar.locator('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
    await sidebar.getByRole('button', { name: 'Tampilkan maskot berikutnya' }).click()
  }
})

test('timer starts on typing, records mistakes, and replays the same text with a ghost', async ({ page }) => {
  await page.clock.install()
  await page.goto('/latihan')
  await page.getByRole('navigation', { name: 'Navigasi utama' }).getByRole('link', { name: 'Typing Race', exact: true }).click()
  await page.locator('#race-duration').selectOption('15')
  await page.locator('#race-length').selectOption('50')
  const source = await page.locator('.race-source').textContent()
  await page.clock.fastForward(3000)
  await expect(page.getByRole('timer')).toHaveText('15dtk')
  const input = page.locator('#race-input')
  await page.locator('.race-editor').click()
  await expect(input).toBeFocused()
  await input.pressSequentially('x')
  await expect(page.locator('.race-track .wrong')).toHaveCount(1)
  await expect(page.locator('#race-duration')).toBeDisabled()
  await page.clock.fastForward(1000)
  await input.pressSequentially('x')
  await page.clock.fastForward(14000)
  await expect(page.getByRole('heading', { name: 'Race selesai!' })).toBeVisible()
  await expect(input).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Arena typing race' })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Pengaturan typing race' })).toHaveCount(0)
  await expect(page.getByTestId('result-accuracy')).toHaveText('0%')
  await expect(page.getByRole('img', { name: /Grafik WPM dan raw WPM/ })).toBeVisible()
  await expect(page.locator('.result-secondary')).toContainText('Konsistensi')
  await page.getByRole('button', { name: 'Ulangi teks + ghost' }).click()
  await expect(input).toBeFocused()
  await expect(page.locator('.race-source')).toHaveText(source!)
  await expect(page.locator('.race-track .ghost')).toHaveCount(1)
  await input.pressSequentially('a')
  await page.clock.fastForward(1100)
  await expect(page.locator('.race-track > span').nth(2)).toHaveClass(/ghost/)
  await page.getByLabel('Ghost percobaan terakhir').uncheck()
  await expect(page.locator('.race-track .ghost')).toHaveCount(0)
})

test('completing romaji scores WPM and new settings clear the previous ghost', async ({ page }) => {
  await page.clock.install()
  await page.goto('/typing-race')
  await page.locator('#race-length').selectOption('50')
  await page.getByLabel('Tampilkan petunjuk romaji').check()
  const target = (await page.locator('.race-track').innerText()).replaceAll('\u00a0', ' ').trimEnd()
  const input = page.locator('#race-input')
  await input.pressSequentially(target[0]!)
  await page.clock.fastForward(5000)
  await input.pressSequentially(target.slice(1))
  await expect(page.getByRole('heading', { name: 'Race selesai!' })).toBeVisible()
  await expect(page.getByTestId('result-accuracy')).toHaveText('100%')
  expect(Number(await page.getByTestId('result-wpm').textContent())).toBeGreaterThan(0)
  await expect(page.locator('#race-result-title')).toBeFocused()
  await expect(page.locator('.speed-chart polyline')).toHaveCount(2)
  await page.screenshot({ path: '.cache/typing-race-results-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '.cache/typing-race-results-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Ulangi teks + ghost' }).click()
  await expect(page.locator('.race-track .ghost')).toHaveCount(1)
  await page.locator('#race-script').selectOption('hangul')
  await page.locator('#race-kind').selectOption('word')
  await expect(page.locator('.race-track .ghost')).toHaveCount(0)
  await expect(page.locator('.race-source')).toHaveAttribute('lang', 'ko')
  await expect(input).toHaveValue('')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '.cache/typing-race-mobile.png', fullPage: true })
})
